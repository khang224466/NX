export function buildVerifiedCombinationsFile() {
  const targetPath = path.resolve(__dirname, '../src/data/verifiedAdmissionDatabase.ts');
  let currentCode = fs.readFileSync(targetPath, 'utf-8');

  // Replace VERIFIED_COMBINATIONS_219
  const startIndex = currentCode.indexOf('export const VERIFIED_COMBINATIONS_219: SubjectComboItem[] = [');
  const endIndex = currentCode.indexOf('export const VERIFIED_UNIVERSITIES: VerifiedUniversity[] = [');

  if (startIndex !== -1 && endIndex !== -1) {
    const newCombinationsString = `export const VERIFIED_COMBINATIONS_219: SubjectComboItem[] = ${JSON.stringify(EXPANDED_COMBINATIONS, null, 2)};\n\n/**\n * DANH SÁCH CÁC ĐẠI HỌC HÀNG ĐẦU VIỆT NAM (BẮC - TRUNG - NAM - ĐBSCL) VỚI ĐỐI SOÁT CHÍNH THỨC\n */\n`;
    currentCode = currentCode.slice(0, startIndex) + newCombinationsString + currentCode.slice(endIndex);
    fs.writeFileSync(targetPath, currentCode, 'utf-8');
    console.log(`✓ Đã cập nhật ${EXPANDED_COMBINATIONS.length} tổ hợp xét tuyển mở rộng vào verifiedAdmissionDatabase.ts`);
  } else {
    console.warn('Could not locate markers for VERIFIED_COMBINATIONS_219 replacement');
  }
}

